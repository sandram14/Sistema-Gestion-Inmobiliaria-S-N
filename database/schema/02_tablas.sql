-- =====================================================================
-- S&N Inmobiliaria - 02: Tablas
-- =====================================================================
-- Convenciones:
--   * Claves primarias numéricas (IDENTITY), salvo barrio.id_barrio,
--     que es la CLAVE_BAR oficial (decisión aprobada en la Fase 2).
--   * Coordenadas en WGS84 (SRID 4326), el mismo sistema que usa Leaflet.
--   * Reglas que involucran varias tablas: ver 04_triggers.sql.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Usuarios administrativos
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id_rol       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       varchar(30)  NOT NULL UNIQUE,
    descripcion  varchar(200)
);

CREATE TABLE usuario (
    id_usuario     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         varchar(60)  NOT NULL,
    apellido       varchar(60)  NOT NULL,
    cedula         varchar(20)  UNIQUE,
    email          varchar(120) NOT NULL,
    telefono       varchar(30),
    password_hash  varchar(60)  NOT NULL,          -- BCrypt: siempre 60 caracteres
    id_rol         integer      NOT NULL REFERENCES rol (id_rol),
    activo         boolean      NOT NULL DEFAULT true,
    debe_cambiar_password boolean NOT NULL DEFAULT false,  -- contraseña temporal (migración 002)
    creado_en      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_email         CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_usuario_password_hash CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$.{53}$')
);
-- El email es único sin distinguir mayúsculas: índice en 03_indices.sql

-- ---------------------------------------------------------------------
-- Ubicación: Departamento -> Ciudad -> Barrio
-- ---------------------------------------------------------------------
CREATE TABLE departamento (
    id_departamento  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           varchar(60) NOT NULL UNIQUE,
    codigo           char(2)     NOT NULL UNIQUE      -- código oficial (Alto Paraná = 10)
);

CREATE TABLE ciudad (
    id_ciudad        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           varchar(80) NOT NULL,
    codigo_distrito  char(2)     NOT NULL,            -- código oficial del distrito
    id_departamento  integer     NOT NULL REFERENCES departamento (id_departamento),
    centro           geometry(Point, 4326) NOT NULL,  -- punto donde se dibuja la ciudad en el mapa
    CONSTRAINT uq_ciudad_nombre UNIQUE (id_departamento, nombre),
    CONSTRAINT uq_ciudad_codigo UNIQUE (id_departamento, codigo_distrito)
);

CREATE TABLE barrio (
    id_barrio  integer      PRIMARY KEY,              -- CLAVE_BAR oficial, no autogenerada
    nombre     varchar(100) NOT NULL,
    id_ciudad  integer      NOT NULL REFERENCES ciudad (id_ciudad),
    geom       geometry(MultiPolygon, 4326) NOT NULL, -- polígono del barrio
    CONSTRAINT uq_barrio_nombre UNIQUE (id_ciudad, nombre),
    CONSTRAINT ck_barrio_geom_valida CHECK (ST_IsValid(geom))
);

-- ---------------------------------------------------------------------
-- Catálogos
-- ---------------------------------------------------------------------
CREATE TABLE tipo_propiedad (
    id_tipo_propiedad  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             varchar(30) NOT NULL UNIQUE    -- Casa, Terreno
);

CREATE TABLE estado_propiedad (
    id_estado  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     varchar(30) NOT NULL UNIQUE            -- Disponible, Reservado, Vendido, Alquilado, Inactivo
);

CREATE TABLE operacion (
    id_operacion  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        varchar(30) NOT NULL UNIQUE         -- Venta, Alquiler
);

-- ---------------------------------------------------------------------
-- Propiedades
-- ---------------------------------------------------------------------
CREATE TABLE propiedad (
    id_propiedad       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             varchar(20)   NOT NULL UNIQUE,  -- código público: prop-001, terr-001
    titulo             varchar(150)  NOT NULL,
    descripcion        text,
    direccion          varchar(200),
    latitud            numeric(9, 6) NOT NULL,
    longitud           numeric(9, 6) NOT NULL,
    -- Calculada por PostgreSQL a partir de latitud/longitud: nunca se desincroniza.
    ubicacion          geometry(Point, 4326)
                       GENERATED ALWAYS AS (
                           ST_SetSRID(ST_MakePoint(longitud::double precision, latitud::double precision), 4326)
                       ) STORED,
    id_tipo_propiedad  integer NOT NULL REFERENCES tipo_propiedad (id_tipo_propiedad),
    id_estado          integer NOT NULL REFERENCES estado_propiedad (id_estado),
    id_barrio          integer NOT NULL REFERENCES barrio (id_barrio),
    id_responsable     integer REFERENCES usuario (id_usuario) ON DELETE SET NULL,  -- migración 002
    creado_en          timestamptz NOT NULL DEFAULT now(),
    actualizado_en     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_propiedad_codigo   CHECK (codigo ~ '^[a-z]+-[0-9]{3,}$'),
    CONSTRAINT ck_propiedad_titulo   CHECK (btrim(titulo) <> ''),
    CONSTRAINT ck_propiedad_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_propiedad_longitud CHECK (longitud BETWEEN -180 AND 180)
);

-- Datos específicos de una Casa (relación 1 a 1 con propiedad)
CREATE TABLE casa (
    id_casa                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propiedad           bigint   NOT NULL UNIQUE REFERENCES propiedad (id_propiedad) ON DELETE CASCADE,
    habitaciones           smallint NOT NULL,
    banos                  smallint NOT NULL,
    sala                   boolean  NOT NULL DEFAULT false,
    comedor                boolean  NOT NULL DEFAULT false,
    cocina                 boolean  NOT NULL DEFAULT false,
    superficie_construida  numeric(10, 2) NOT NULL,     -- m²
    superficie_terreno     numeric(10, 2),              -- m², opcional
    CONSTRAINT ck_casa_habitaciones CHECK (habitaciones >= 0),
    CONSTRAINT ck_casa_banos        CHECK (banos >= 0),
    CONSTRAINT ck_casa_sup_constr   CHECK (superficie_construida > 0),
    CONSTRAINT ck_casa_sup_terreno  CHECK (superficie_terreno IS NULL OR superficie_terreno > 0)
);

-- Datos específicos de un Terreno (relación 1 a 1 con propiedad)
CREATE TABLE terreno (
    id_terreno    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propiedad  bigint  NOT NULL UNIQUE REFERENCES propiedad (id_propiedad) ON DELETE CASCADE,
    superficie    numeric(12, 2) NOT NULL,              -- m²
    frente        numeric(8, 2),                        -- m
    fondo         numeric(8, 2),                        -- m
    tiene_titulo  boolean NOT NULL DEFAULT false,       -- cuenta con título de propiedad
    CONSTRAINT ck_terreno_superficie CHECK (superficie > 0),
    CONSTRAINT ck_terreno_frente     CHECK (frente IS NULL OR frente > 0),
    CONSTRAINT ck_terreno_fondo      CHECK (fondo  IS NULL OR fondo  > 0)
);

-- Imágenes (1 propiedad -> N imágenes)
CREATE TABLE imagen (
    id_imagen     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propiedad  bigint       NOT NULL REFERENCES propiedad (id_propiedad) ON DELETE CASCADE,
    url           varchar(500) NOT NULL,
    descripcion   varchar(200),
    es_principal  boolean      NOT NULL DEFAULT false,
    orden         smallint     NOT NULL DEFAULT 0,      -- orden en el carrusel
    CONSTRAINT uq_imagen_url   UNIQUE (id_propiedad, url),
    CONSTRAINT ck_imagen_url   CHECK (url ~ '^(/|https://)'),
    CONSTRAINT ck_imagen_orden CHECK (orden >= 0)
);
-- "Como máximo una imagen principal por propiedad": índice parcial en 03_indices.sql

-- Operaciones de cada propiedad, con su precio y moneda
CREATE TABLE operacion_propiedad (
    id_propiedad  bigint  NOT NULL REFERENCES propiedad (id_propiedad) ON DELETE CASCADE,
    id_operacion  integer NOT NULL REFERENCES operacion (id_operacion),
    precio        numeric(15, 2) NOT NULL,
    moneda        char(3) NOT NULL,
    PRIMARY KEY (id_propiedad, id_operacion),
    CONSTRAINT ck_operacion_precio CHECK (precio > 0),
    CONSTRAINT ck_operacion_moneda CHECK (moneda IN ('PYG', 'USD'))
);

-- ---------------------------------------------------------------------
-- Consultas al asistente de IA
-- ---------------------------------------------------------------------
CREATE TABLE consulta (
    id_consulta   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion     uuid        NOT NULL,                  -- cookie de sesión del visitante
    consulta      text        NOT NULL,
    respuesta     text,
    id_propiedad  bigint      REFERENCES propiedad (id_propiedad) ON DELETE SET NULL,
    fecha_hora    timestamptz NOT NULL DEFAULT now(),
    -- Migración 003: resultado registrado por el backend y revisión interna del equipo
    resultado       varchar(20) CONSTRAINT ck_consulta_resultado CHECK (resultado IN ('RESPONDIDA', 'DERIVADA_ASESOR', 'SIN_SERVICIO', 'BLOQUEADA', 'FUERA_DE_AMBITO')),
    estado_revision varchar(10) NOT NULL DEFAULT 'PENDIENTE' CONSTRAINT ck_consulta_revision CHECK (estado_revision IN ('PENDIENTE', 'REVISADA')),
    revisada_por    integer REFERENCES usuario (id_usuario) ON DELETE SET NULL,
    revisada_en     timestamptz,
    CONSTRAINT ck_consulta_texto CHECK (char_length(btrim(consulta)) BETWEEN 1 AND 2000)
);

-- Propiedades recomendadas por el asistente en cada consulta (migración 003)
CREATE TABLE consulta_recomendacion (
    id_consulta  bigint NOT NULL REFERENCES consulta (id_consulta) ON DELETE CASCADE,
    id_propiedad bigint NOT NULL REFERENCES propiedad (id_propiedad) ON DELETE CASCADE,
    PRIMARY KEY (id_consulta, id_propiedad)
);
