-- =====================================================================
-- Migración 011: auditoría de accesos y cierre de sesiones al restablecer una contraseña
-- =====================================================================
-- * usuario.version_credencial: número que sube cada vez que el administrador restablece la contraseña de
--   un usuario. Cada sesión recuerda el número con el que se abrió; si ya no coincide, la sesión se cierra.
-- * auditoria: quién restableció la contraseña temporal de quién y cuándo. Nunca guarda contraseñas.
-- No modifica ningún usuario existente (todos quedan con version_credencial = 0).
-- Uso: docker compose -f docker/docker-compose.yml exec db psql -U sn_app -d sn_inmobiliaria -v ON_ERROR_STOP=1 -f /database/migraciones/011_auditoria_y_sesiones.sql
-- =====================================================================
\set ON_ERROR_STOP on
BEGIN;
CREATE TEMP TABLE antes ON COMMIT DROP AS
    SELECT id_usuario, email, password_hash, id_rol, activo, debe_cambiar_password FROM usuario;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'usuario' AND column_name = 'version_credencial')
       OR to_regclass('public.auditoria') IS NOT NULL THEN
        RAISE EXCEPTION 'La migración 011 ya está aplicada. Nada fue modificado.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'usuario' AND column_name = 'debe_cambiar_password') THEN
        RAISE EXCEPTION 'Falta la migración 002 (usuario.debe_cambiar_password). Nada fue modificado.';
    END IF;
END $$;

ALTER TABLE usuario ADD COLUMN version_credencial integer NOT NULL DEFAULT 0
    CONSTRAINT ck_usuario_version_credencial CHECK (version_credencial >= 0);

CREATE TABLE auditoria (
    id_auditoria        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha               timestamptz NOT NULL DEFAULT now(),
    accion              varchar(40) NOT NULL
        CONSTRAINT ck_auditoria_accion CHECK (accion IN ('CONTRASENA_TEMPORAL_RESTABLECIDA')),
    id_actor            integer REFERENCES usuario (id_usuario) ON DELETE SET NULL,
    id_usuario_afectado integer REFERENCES usuario (id_usuario) ON DELETE SET NULL
);
CREATE INDEX ix_auditoria_fecha ON auditoria (fecha);
CREATE INDEX ix_auditoria_afectado ON auditoria (id_usuario_afectado);

DO $$
BEGIN
    IF (SELECT count(*) FROM usuario) <> (SELECT count(*) FROM antes)
       OR EXISTS (SELECT 1 FROM antes a JOIN usuario u USING (id_usuario)
                  WHERE u.email IS DISTINCT FROM a.email OR u.password_hash IS DISTINCT FROM a.password_hash
                     OR u.id_rol IS DISTINCT FROM a.id_rol OR u.activo IS DISTINCT FROM a.activo
                     OR u.debe_cambiar_password IS DISTINCT FROM a.debe_cambiar_password
                     OR u.version_credencial <> 0) THEN
        RAISE EXCEPTION 'Los usuarios cambiaron. Se deshace todo.';
    END IF;
    RAISE NOTICE 'OK: migración 011 aplicada. % usuarios sin cambios; auditoría creada (vacía).', (SELECT count(*) FROM usuario);
END $$;
COMMIT;
