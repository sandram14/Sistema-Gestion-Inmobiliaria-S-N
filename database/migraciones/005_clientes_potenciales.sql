-- =====================================================================
-- Migración 005: clientes potenciales (panel, etapa 3, entrega 2)
-- =====================================================================
-- Crea la tabla cliente_potencial. No modifica ninguna tabla ni dato existente.
-- Datos personales mínimos: nombre, teléfono y/o email y el detalle del interés. No se guarda IP.
-- Uso: docker compose -f docker/docker-compose.yml exec db psql -U sn_app -d sn_inmobiliaria -v ON_ERROR_STOP=1 -f /database/migraciones/005_clientes_potenciales.sql
-- =====================================================================
\set ON_ERROR_STOP on
BEGIN;
CREATE TEMP TABLE conteos_antes ON COMMIT DROP AS
SELECT (SELECT count(*) FROM propiedad) AS p, (SELECT count(*) FROM consulta) AS c, (SELECT count(*) FROM usuario) AS u;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'cliente_potencial') THEN
        RAISE EXCEPTION 'La tabla cliente_potencial ya existe: la migración 005 parece aplicada. Nada fue modificado.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_consulta_resultado' AND pg_get_constraintdef(oid) LIKE '%FUERA_DE_AMBITO%') THEN
        RAISE EXCEPTION 'Falta la migración 004 (aplíquela primero). Nada fue modificado.';
    END IF;
END $$;
CREATE TABLE cliente_potencial (
    id_cliente_potencial bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          varchar(120) NOT NULL,
    telefono        varchar(30),
    email           varchar(120),
    interes         varchar(1000),
    id_propiedad    bigint  REFERENCES propiedad (id_propiedad) ON DELETE SET NULL,
    id_consulta     bigint  REFERENCES consulta (id_consulta) ON DELETE SET NULL,
    origen          varchar(10) NOT NULL,
    estado          varchar(12) NOT NULL DEFAULT 'PENDIENTE',
    id_responsable  integer REFERENCES usuario (id_usuario) ON DELETE SET NULL,
    registrado_por  integer REFERENCES usuario (id_usuario) ON DELETE SET NULL,
    -- Aceptación del tratamiento de datos (obligatoria cuando el cliente se registra desde el chat)
    consentimiento_en      timestamptz,
    consentimiento_version varchar(20),
    creado_en       timestamptz NOT NULL DEFAULT now(),
    actualizado_en  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_cliente_nombre CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 120),
    CONSTRAINT ck_cliente_contacto CHECK (telefono IS NOT NULL OR email IS NOT NULL),
    CONSTRAINT ck_cliente_email CHECK (email IS NULL OR email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_cliente_origen CHECK (origen IN ('CHAT', 'WHATSAPP', 'LLAMADA', 'OTRO')),
    CONSTRAINT ck_cliente_estado CHECK (estado IN ('PENDIENTE', 'CONTACTADO', 'DESCARTADO')),
    CONSTRAINT ck_cliente_consentimiento CHECK (origen <> 'CHAT' OR (consentimiento_en IS NOT NULL AND consentimiento_version IS NOT NULL))
);
CREATE INDEX ix_cliente_responsable ON cliente_potencial (id_responsable);
CREATE INDEX ix_cliente_estado ON cliente_potencial (estado);
CREATE INDEX ix_cliente_creado ON cliente_potencial (creado_en);
DO $$
BEGIN
    IF (SELECT p FROM conteos_antes) <> (SELECT count(*) FROM propiedad) OR (SELECT c FROM conteos_antes) <> (SELECT count(*) FROM consulta)
       OR (SELECT u FROM conteos_antes) <> (SELECT count(*) FROM usuario) THEN
        RAISE EXCEPTION 'Cambiaron datos existentes. Se deshace todo.';
    END IF;
    RAISE NOTICE 'OK: migración 005 aplicada. Tabla cliente_potencial creada (vacía); propiedades, consultas y usuarios sin cambios.';
END $$;
COMMIT;
